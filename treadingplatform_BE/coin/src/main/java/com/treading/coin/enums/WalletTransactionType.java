package com.treading.coin.enums;

/**
 * The enum Wallet transaction type.
 */
public enum WalletTransactionType {
	/**
	 * Withdrawal wallet transaction type.
	 */
	WITHDRAWAL,
	/**
	 * Wallet transfer wallet transaction type.
	 */
	WALLET_TRANSFER,
	/**
	 * Add money wallet transaction type.
	 */
	ADD_MONEY,
	/**
	 * Buy asset wallet transaction type.
	 */
	BUY_ASSET,
	/**
	 * Sell asset wallet transaction type.
	 */
	SELL_ASSET
}
